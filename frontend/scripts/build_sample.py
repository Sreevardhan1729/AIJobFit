def build_pdf(text: str) -> bytes:
    """One page, one text-show per line, so PyPDF2 keeps the line breaks."""

    def escape(line: str) -> str:
        return line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")

    ops = ["BT", "/F1 10 Tf", "56 760 Td"]
    for line in text.splitlines():
        ops.append(f"({escape(line)}) Tj")
        ops.append("0 -15 Td")
    ops.append("ET")
    stream = "\n".join(ops).encode("cp1252")  # matches the font's WinAnsiEncoding ("·")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R "
        b"/Resources << /Font << /F1 5 0 R >> >> >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode()
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return bytes(out)


def ts_module(name: str, text: str) -> str:
    literal = json.dumps(text, ensure_ascii=False)
    return f"// Generated by scripts/build_sample.py. Do not edit by hand.\nexport const {name} = {literal};\n"


def capture(backend_url: str) -> dict:
    boundary = uuid.uuid4().hex
    body = (
        f'--{boundary}\r\nContent-Disposition: form-data; name="job_description"\r\n\r\n'.encode()
        + JOB_TEXT.encode("utf-8")
        + f'\r\n--{boundary}\r\nContent-Disposition: form-data; name="resume"; filename="sample-resume.pdf"\r\n'
        "Content-Type: application/pdf\r\n\r\n".encode()
        + PDF_PATH.read_bytes()
        + f"\r\n--{boundary}--\r\n".encode()
    )
    request = urllib.request.Request(
        backend_url.rstrip("/") + "/match",
        data=body,
        headers={"Content-Type": f"multipart/form-data; boundary={boundary}"},
    )
    with urllib.request.urlopen(request, timeout=180) as response:
        return json.load(response)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--capture", metavar="BACKEND_URL", help="also save a real /match result for the sample")
    args = parser.parse_args()

    PDF_PATH.parent.mkdir(parents=True, exist_ok=True)
    PDF_PATH.write_bytes(build_pdf(RESUME_TEXT))
    RESUME_TS.write_text(ts_module("SAMPLE_RESUME_TEXT", RESUME_TEXT), encoding="utf-8")
    JOB_TS.write_text(ts_module("SAMPLE_JOB_TEXT", JOB_TEXT), encoding="utf-8")
    print(f"wrote {PDF_PATH.relative_to(FRONTEND)}, {RESUME_TS.relative_to(FRONTEND)}, {JOB_TS.relative_to(FRONTEND)}")

    if args.capture:
        result = capture(args.capture)
        MATCH_JSON.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {MATCH_JSON.relative_to(FRONTEND)} (score {result['score']})")


if __name__ == "__main__":
    main()
